/**
 * Live Grok gate. Builds nothing by itself — point it at a running server that
 * was started with XAI_API_KEY and GENERATOR=grok (default).
 *
 *   XAI_API_KEY=... npm start
 *   BASE_URL=http://localhost:8080 node scripts/live-grok.mjs
 *
 * Hits POST /api/generate for real, then drives the UI in Chromium and asks the
 * voice socket for one spoken turn. Exits 2 when XAI_API_KEY is missing.
 * A passing run is the only thing that counts as live Grok validation.
 */
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import WebSocket from 'ws';

const BASE = process.env.BASE_URL || 'http://localhost:8080';

if (!process.env.XAI_API_KEY) {
  console.error('LIVE GROK VALIDATION: NOT DONE');
  console.error('Missing secret: XAI_API_KEY');
  console.error('Set XAI_API_KEY and GENERATOR=grok (the default), start the server, then re-run this script.');
  console.error('Optional: GROK_MODEL (default grok-4.7), XAI_BASE_URL (default https://api.x.ai/v1).');
  process.exit(2);
}

const shots = new URL('./screens/', import.meta.url);
mkdirSync(shots, { recursive: true });

const health = await fetch(`${BASE}/api/health`);
if (!health.ok) throw new Error(`health ${health.status} — is the server running at ${BASE}?`);
const healthBody = await health.json();
if (healthBody.generator !== 'grok') {
  throw new Error(`server generator is ${healthBody.generator}, expected grok`);
}

const generated = await fetch(`${BASE}/api/generate`, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ prompt: 'a counter with a plus button and a minus button' }),
});
const body = await generated.json();
if (!generated.ok || body.degraded || body.source !== 'grok' || !Array.isArray(body.spec?.tree) || body.spec.tree.length === 0) {
  throw new Error(`live generate did not return a Grok spec: ${JSON.stringify({ status: generated.status, source: body.source, degraded: body.degraded, title: body.spec?.title })}`);
}
console.log(`[PASS] POST /api/generate source=grok model=${healthBody.model} title=${body.spec.title}`);

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
try {
  await page.goto(BASE, { waitUntil: 'domcontentloaded' });
  const box = page.getByRole('textbox', { name: /describe an interface/i });
  await box.fill('a counter with plus and minus buttons showing the count');
  await box.press('Enter');
  await page.getByText(/Generated by Grok/i).waitFor({ timeout: 90000 });
  await page.screenshot({ path: new URL('./screens/live-grok.png', import.meta.url).pathname });
  console.log('[PASS] browser showed Generated by Grok');

  // `ws`, not the global WebSocket: Node 20 only exposes that global behind
  // --experimental-websocket. Node 22 has it built in. This works on both.
  const voice = await new Promise((resolve, reject) => {
    const ws = new WebSocket(BASE.replace(/^http/, 'ws') + '/voice');
    const timer = setTimeout(() => { ws.close(); reject(new Error('voice timed out')); }, 45000);
    const fail = (err) => { clearTimeout(timer); ws.close(); reject(err); };
    ws.on('error', (err) => fail(err instanceof Error ? err : new Error(String(err))));
    ws.on('message', (data) => {
      const msg = JSON.parse(data.toString());
      if (msg.type === 'ready') {
        ws.send(JSON.stringify({ type: 'text', text: 'Say hello in one short sentence.' }));
      } else if (msg.type === 'audio' || (msg.type === 'transcript' && msg.who === 'ai' && msg.text)) {
        clearTimeout(timer);
        ws.close();
        resolve(msg.type);
      } else if (msg.type === 'error') {
        fail(new Error(msg.message || 'voice error'));
      }
    });
    ws.on('open', () => {
      ws.send(JSON.stringify({ type: 'init', spec: body.spec, readable: body.spec.title || '' }));
    });
  });
  console.log(`[PASS] voice socket returned ${voice}`);
} finally {
  await browser.close();
}

console.log('LIVE GROK VALIDATION: DONE');
