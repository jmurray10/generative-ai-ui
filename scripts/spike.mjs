/** Spike validation: capture the streaming "build itself" sequence —
 *  skeleton -> build log/progress -> provenance. Run with a slow stagger. */
import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const BASE = process.env.BASE_URL || 'http://localhost:8080';
const SHOTS = join(dirname(fileURLToPath(import.meta.url)), 'screens');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 900, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
try {
  await page.goto(BASE, { waitUntil: 'networkidle' });
  await page.getByRole('textbox').first().fill(
    'a dashboard with three separate stacked cards: a KPI metrics card, a bar chart card of monthly revenue, and a checklist card',
  );
  await page.getByRole('button', { name: /generate/i }).click();

  try { await page.getByText(/reading your prompt/i).waitFor({ timeout: 8000 }); await page.screenshot({ path: join(SHOTS, 'spike-1-skeleton.png') }); console.log('captured skeleton'); }
  catch { console.log('skeleton not caught'); }

  try { await page.getByText(/assembling the interface/i).waitFor({ timeout: 40000 }); await page.waitForTimeout(350); await page.screenshot({ path: join(SHOTS, 'spike-2-building.png') }); console.log('captured building'); }
  catch { console.log('building not caught'); }

  try { await page.getByText(/generated by gemini/i).waitFor({ timeout: 40000 }); await page.screenshot({ path: join(SHOTS, 'spike-3-done.png'), fullPage: true }); console.log('captured done'); }
  catch { console.log('done not caught'); }

  console.log('console errors:', errors.length);
} finally {
  await browser.close();
}
